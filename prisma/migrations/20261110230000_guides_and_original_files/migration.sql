 "uploadId" TEXT NOT NULL PRIMARY KEY,
 "contents" BLOB NOT NULL,
 "mimeType" TEXT NOT NULL,
 "sha256" TEXT NOT NULL,
 "createdAt" DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
